"""
STK Astrogator Object Model probe (requires a live STK 13 + Astrogator licence).

Discovers the real property/method names needed to build an Astrogator MCS with
an N-Plate SRP model, N-Plate drag, USStandardAtmosphere, and configurable
eclipse/shadow — the names the plan marked with a warning as needing runtime
confirmation (risks R2/R4/R5).

It is DEFENSIVE: every access is wrapped, and it dumps dir() listings and
collection contents so we can read off the true API even where our guesses are
wrong. Findings are written to docs/astrogator_design.md and echoed to stdout.

Run:  python validation/probe_astrogator.py         (from the "STK simulations" dir)
"""

from __future__ import annotations

import os
import sys
import traceback

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.dirname(_HERE)
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

OUT_MD = os.path.join(_ROOT, "docs", "astrogator_design.md")
_lines = []


def emit(s=""):
    print(s)
    _lines.append(s)


def members(obj):
    try:
        return [m for m in dir(obj) if not m.startswith("_")]
    except Exception as e:
        return [f"<dir failed: {e}>"]


def dump(label, obj, show_type=True):
    emit(f"\n### {label}")
    if show_type:
        emit(f"- type: `{type(obj)}`")
    ms = members(obj)
    emit(f"- members ({len(ms)}): " + ", ".join(f"`{m}`" for m in ms))


def dump_collection(label, coll):
    emit(f"\n### {label} (collection)")
    try:
        n = coll.Count
        emit(f"- Count = {n}")
        for i in range(n):
            it = coll.Item(i)
            name = getattr(it, "Name", None)
            typ = getattr(it, "Type", None)
            emit(f"  - [{i}] Name=`{name}` Type=`{typ}` pytype=`{type(it).__name__}`")
    except Exception as e:
        emit(f"- <enumerate failed: {e}>")


def try_call(label, fn):
    try:
        v = fn()
        emit(f"- {label}: OK -> `{v!r}`"[:400])
        return v
    except Exception as e:
        emit(f"- {label}: FAIL ({type(e).__name__}: {e})"[:400])
        return None


def main():
    emit("# STK Astrogator Object Model — probe findings")
    emit("")
    emit("Auto-generated by validation/probe_astrogator.py against the live STK build.")
    emit("Names below are authoritative for this machine; hard-code them in the builders.")

    # ---- session -----------------------------------------------------------
    from agi.stk13 import stkobjects as o
    emit("\n## Session")
    app = None
    started = False
    root = None
    try:
        from agi.stk13.stkengine import STKEngine
        app = STKEngine.StartApplication(noGraphics=True)
        root = app.NewObjectRoot()
        started = True
        emit("- Started STKEngine (headless).")
    except Exception as e:
        emit(f"- STKEngine unavailable ({type(e).__name__}: {e}); trying Desktop.")
        from agi.stk13.stkdesktop import STKDesktop
        try:
            app = STKDesktop.AttachToApplication()
            emit("- Attached to running STK Desktop.")
        except Exception:
            app = STKDesktop.StartApplication(visible=False, userControl=False)
            started = True
            emit("- Started STK Desktop (headless-ish).")
        root = app.Root

    try:
        # Is the astrogator submodule importable? (class names live there)
        try:
            import agi.stk13.stkobjects.astrogator as astro
            emit(f"- astrogator submodule OK; classes (first 40): "
                 + ", ".join(members(astro)[:40]))
        except Exception as e:
            emit(f"- astrogator submodule import: FAIL ({type(e).__name__}: {e})")

        try:
            root.CloseScenario()
        except Exception:
            pass
        root.NewScenario("Probe")
        scen = root.CurrentScenario
        scen.SetTimePeriod("1 Jan 2026 12:00:00.000", "2 Jan 2026 12:00:00.000")
        sat = scen.Children.New(o.AgESTKObjectType.eSatellite, "Probe")
        emit("- scenario + satellite created.")

        # ---- set Astrogator ------------------------------------------------
        emit("\n## Propagator = Astrogator")
        try_call("SetPropagatorType(ePropagatorAstrogator)",
                 lambda: sat.SetPropagatorType(o.AgEVePropagatorType.ePropagatorAstrogator))
        driver = sat.Propagator
        dump("driver (sat.Propagator)", driver)

        # ---- MCS main sequence + segments ----------------------------------
        emit("\n## MCS main sequence")
        mcs = try_call("driver.MainSequence", lambda: driver.MainSequence)
        if mcs is not None:
            dump_collection("MainSequence segments", mcs)
            # dump each segment's members + stopping conditions if present
            try:
                for i in range(mcs.Count):
                    seg = mcs.Item(i)
                    dump(f"segment[{i}] Name={getattr(seg,'Name',None)}", seg)
                    # stopping conditions (Propagate segments)
                    if hasattr(seg, "StoppingConditions"):
                        try:
                            sc = seg.StoppingConditions
                            dump_collection(f"segment[{i}].StoppingConditions", sc)
                            if sc.Count:
                                stop0 = sc.Item(0)
                                dump(f"segment[{i}].StoppingConditions[0]", stop0)
                                if hasattr(stop0, "Properties"):
                                    dump(f"segment[{i}].StoppingConditions[0].Properties",
                                         stop0.Properties)
                        except Exception as e:
                            emit(f"- stopping conditions dump failed: {e}")
                    # Initial-state element access
                    for attr in ("Element", "OrbitEpoch", "CoordSystemName",
                                 "PropagatorName"):
                        if hasattr(seg, attr):
                            try_call(f"segment[{i}].{attr}", lambda a=attr, s=seg: getattr(s, a))
                    if hasattr(seg, "Element"):
                        try:
                            dump(f"segment[{i}].Element", seg.Element)
                        except Exception as e:
                            emit(f"- Element dump failed: {e}")
            except Exception as e:
                emit(f"- segment iteration failed: {e}")

        # ---- numerical propagator + force functions ------------------------
        emit("\n## Numerical propagator components")
        # Astrogator component directory: try several access paths.
        compdir = None
        for label, getter in (
            ("root.CurrentScenario.ComponentDirectory",
             lambda: root.CurrentScenario.ComponentDirectory),
            ("driver.ComponentDirectory", lambda: driver.ComponentDirectory),
            ("scen.ComponentDirectory", lambda: scen.ComponentDirectory),
        ):
            compdir = try_call(label, getter)
            if compdir is not None:
                dump(label, compdir)
                break

        # Component directory typically has GetComponents by category.
        if compdir is not None:
            for cat in ("Propagators", "AtmosphericDensityModels",
                        "SolarRadiationPressureModels"):
                try_call(f"compdir.GetComponents('{cat}')",
                         lambda c=cat: compdir.GetComponents(c))

        # Try to reach a Propagate segment's numerical propagator directly.
        emit("\n## Propagate segment -> numerical propagator + PropagatorFunctions")
        propseg = None
        try:
            for i in range(mcs.Count):
                seg = mcs.Item(i)
                if "propagate" in str(getattr(seg, "Name", "")).lower():
                    propseg = seg
                    break
        except Exception:
            pass
        if propseg is not None:
            for attr in ("Propagator", "PropagatorName"):
                v = try_call(f"propseg.{attr}", lambda a=attr: getattr(propseg, a))
                if attr == "Propagator" and v is not None:
                    dump("propseg.Propagator (numerical propagator)", v)
                    for a2 in ("PropagatorFunctions", "Integrator",
                               "NumericalIntegrator"):
                        v2 = try_call(f"propseg.Propagator.{a2}", lambda x=a2, vv=v: getattr(vv, x))
                        if v2 is not None and "Function" in a2:
                            dump_collection("PropagatorFunctions", v2)

    finally:
        # write out no matter what
        os.makedirs(os.path.dirname(OUT_MD), exist_ok=True)
        with open(OUT_MD, "w", encoding="utf-8") as f:
            f.write("\n".join(_lines) + "\n")
        emit(f"\n\n(wrote {OUT_MD})")
        if started and app is not None:
            try:
                app.ShutDown()
            except Exception:
                pass


if __name__ == "__main__":
    try:
        main()
    except Exception:
        traceback.print_exc()
        # still flush whatever we gathered
        try:
            os.makedirs(os.path.dirname(OUT_MD), exist_ok=True)
            with open(OUT_MD, "w", encoding="utf-8") as f:
                f.write("\n".join(_lines) + "\n")
        except Exception:
            pass
        sys.exit(1)
